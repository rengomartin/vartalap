package services

import (
	"crypto/hmac"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"strings"
)

const (
	// DeviceTokenVersion is embedded in every signed device token so the
	// format can be rotated without breaking existing deployments.
	DeviceTokenVersion = "v1"
	// DeviceSyncCookieName mirrors the HttpOnly identity cookie in a
	// JavaScript-readable cookie. It lets the client keep a localStorage copy
	// so identity survives browsers that evict cookies aggressively.
	DeviceSyncCookieName = "vartalap_sync"
	// DeviceIDHeader lets a remembered client restore its identity on requests
	// that cannot carry the primary cookie.
	DeviceIDHeader = "X-Vartalap-Device"
)

// IdentitySigner issues and verifies tamper-evident device tokens.
//
// Device IDs are public-looking UUIDs, so a bare cookie is trivially copied.
// Signing the value with a server-held secret makes it impossible to forge a
// token for another device without knowing that secret. The secret is stored
// in the database and survives restarts.
type IdentitySigner struct {
	secret []byte
}

// NewIdentitySigner creates a signer from a secret generated by the server.
func NewIdentitySigner(secret []byte) *IdentitySigner {
	copied := make([]byte, len(secret))
	copy(copied, secret)
	return &IdentitySigner{secret: copied}
}

// Issue returns a signed token for a device ID.
func (s *IdentitySigner) Issue(deviceID string) string {
	return DeviceTokenVersion + "." + deviceID + "." + s.mac(deviceID)
}

// Verify checks a token's signature and returns its device ID.
func (s *IdentitySigner) Verify(token string) (string, bool) {
	parts := strings.Split(token, ".")
	if len(parts) != 3 || parts[0] != DeviceTokenVersion {
		return "", false
	}
	deviceID := parts[1]
	if !IsValidDeviceID(deviceID) {
		return "", false
	}
	expected := s.mac(deviceID)
	if subtle.ConstantTimeCompare([]byte(parts[2]), []byte(expected)) != 1 {
		return "", false
	}
	return deviceID, true
}

func (s *IdentitySigner) mac(deviceID string) string {
	mac := hmac.New(sha256.New, s.secret)
	mac.Write([]byte("vartalap-device-token:" + DeviceTokenVersion + ":"))
	mac.Write([]byte(deviceID))
	return base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}
